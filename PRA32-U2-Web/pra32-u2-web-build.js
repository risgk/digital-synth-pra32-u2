// Builds PRA32-U2 Web: "../pra32-u2-web-synth.js" (loaded by "../pra32-u2-editor.html").
// Requirements: Emscripten (em++ in PATH, e.g. after "emsdk_env") and Node.js (included in emsdk).
// Usage (in this folder): node pra32-u2-web-build.js

"use strict";

const fs = require("fs");
const os = require("os");
const path = require("path");
const { execSync } = require("child_process");

const HERE   = __dirname;
const CORE   = path.join(HERE, "..", "Digital-Synth-PRA32-U2");
const NATIVE = path.join(HERE, "..", "PRA32-U2-Native", "Source");
const OUTPUT = path.join(HERE, "..", "pra32-u2-web-synth.js");

// The version is the same as PRA32-U2 (PRA32_U2_VERSION in Digital-Synth-PRA32-U2.ino)
const ino = fs.readFileSync(path.join(CORE, "Digital-Synth-PRA32-U2.ino"), "utf8");
const versionMatch = ino.match(/^#define PRA32_U2_VERSION\s+"(v[0-9]+\.[0-9]+\.[0-9]+)/m);
if (!versionMatch) {
  throw new Error("PRA32_U2_VERSION is not found in Digital-Synth-PRA32-U2.ino");
}
const version = "PRA32-U2 Web " + versionMatch[1];

// The core and the renderer of PRA32-U2 Native (not modified)
const wasmPath = path.join(fs.mkdtempSync(path.join(os.tmpdir(), "pra32-u2-web-")), "pra32-u2-web.wasm");
const sources = [
  path.join(HERE, "Source", "PRA32U2WebMain.cpp"),
  path.join(NATIVE, "PRA32U2Engine.cpp"),
  path.join(NATIVE, "PRA32U2Renderer.cpp"),
  path.join(NATIVE, "PRA32U2Resampler.cpp"),
];
const command = [
  "em++", "-O3", "-std=c++17", "-fno-exceptions", "-Wno-unknown-attributes",
  "-sSTANDALONE_WASM", "--no-entry", "-sFILESYSTEM=0",
  "-sINITIAL_MEMORY=2MB", "-sSTACK_SIZE=256KB", "-sALLOW_MEMORY_GROWTH=0",
  "-I" + JSON.stringify(NATIVE), "-I" + JSON.stringify(CORE),
  ...sources.map((s) => JSON.stringify(s)),
  "-o", JSON.stringify(wasmPath),
].join(" ");
console.log(command);
execSync(command, { stdio: "inherit" });

const wasm = fs.readFileSync(wasmPath);
fs.rmSync(path.dirname(wasmPath), { recursive: true, force: true });

// Embeds the version, the WebAssembly binary (Base64), and the AudioWorkletProcessor (a string) in the main part
const processor = fs.readFileSync(path.join(HERE, "pra32-u2-web-synth-processor.js"), "utf8");
const main = fs.readFileSync(path.join(HERE, "pra32-u2-web-synth-main.js"), "utf8");
const replace = (text, name, value) => {
  const placeholder = "/*@" + name + "@*/\"\"";
  if (!text.includes(placeholder)) {
    throw new Error(placeholder + " is not found in pra32-u2-web-synth-main.js");
  }
  return text.replace(placeholder, () => JSON.stringify(value));
};
let output = main;
output = replace(output, "PRA32_U2_WEB_VERSION", version);
output = replace(output, "WASM_BASE64", wasm.toString("base64"));
output = replace(output, "PROCESSOR_SOURCE", processor);
output = "// " + version + " (generated by \"PRA32-U2-Web/pra32-u2-web-build.js\", do not edit)\n" + output;

fs.writeFileSync(OUTPUT, output);
console.log("Generated: " + OUTPUT + " (" + output.length + " bytes; WebAssembly: " + wasm.length + " bytes)");
